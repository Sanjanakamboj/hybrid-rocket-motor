"""Independent verification of the nitrous oxide property module.

Independence strategy
---------------------
The reference values below were retrieved separately from the **NIST Chemistry
WebBook** saturation tabulation for nitrous oxide and are hard-coded here.  They
are *not* generated by this project's code.

An important honesty caveat, stated rather than glossed: NIST cites the same
equation of state that CoolProp uses for N2O (Lemmon & Span, J. Chem. Eng. Data
51 (2006) 785-850).  Agreement therefore verifies this module's **units, phase
selection and call structure** -- it does not independently validate the equation
of state itself.  That is exactly what a property-plumbing test should do.

A second, genuinely independent axis is checked as well: the low-level
``AbstractState`` interface used for speed must agree with CoolProp's
string-based ``PropsSI`` interface.
"""

