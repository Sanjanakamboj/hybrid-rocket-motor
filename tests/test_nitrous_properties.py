# --- 4. reference points against source data ------------------------------


@pytest.mark.parametrize(("temperature", "pressure", "rho_l", "rho_v", "h_l", "h_v"),
                         NIST_SATURATION_TABLE)
def test_saturation_properties_match_the_nist_tabulation(
    temperature, pressure, rho_l, rho_v, h_l, h_v
):
    """Tolerances are set by the WebBook's own 5-6 significant figures."""
    assert saturation_pressure_pa(temperature) == pytest.approx(pressure, rel=2.0e-4)
    assert saturated_liquid_density_kg_m3(temperature) == pytest.approx(rho_l, rel=2.0e-5)
    assert saturated_vapour_density_kg_m3(temperature) == pytest.approx(rho_v, rel=2.0e-5)
    assert saturated_liquid_enthalpy_j_kg(temperature) == pytest.approx(h_l * 1e3, rel=2.0e-5)
    assert saturated_vapour_enthalpy_j_kg(temperature) == pytest.approx(h_v * 1e3, rel=2.0e-5)


def test_room_temperature_vapour_pressure_matches_the_literature_value():
    """Waxman et al. quote ~730 psi (5.03 MPa) for N2O at room temperature."""
    assert saturation_pressure_pa(293.15) == pytest.approx(5.03e6, rel=0.01)


def test_low_level_and_string_interfaces_agree():
    """The AbstractState speed optimisation must not change any number."""
    for temperature in (210.0, 250.0, 293.15, 300.0):
        assert saturation_pressure_pa(temperature) == pytest.approx(
            CP.PropsSI("P", "T", temperature, "Q", 0, FLUID), rel=1e-12
        )
        assert saturated_liquid_density_kg_m3(temperature) == pytest.approx(
            CP.PropsSI("D", "T", temperature, "Q", 0, FLUID), rel=1e-12
        )
        assert saturated_vapour_density_kg_m3(temperature) == pytest.approx(
            CP.PropsSI("D", "T", temperature, "Q", 1, FLUID), rel=1e-12
        )
        assert saturated_liquid_internal_energy_j_kg(temperature) == pytest.approx(
            CP.PropsSI("U", "T", temperature, "Q", 0, FLUID), rel=1e-12
        )
        assert saturated_liquid_entropy_j_kg_k(temperature) == pytest.approx(
            CP.PropsSI("S", "T", temperature, "Q", 0, FLUID), rel=1e-12
        )


# --- 1, 2. saturation pressure --------------------------------------------


def test_saturation_pressure_is_positive_everywhere_in_range():
    for temperature, *_ in NIST_SATURATION_TABLE:
        assert saturation_pressure_pa(temperature) > 0.0


def test_saturation_pressure_increases_monotonically_with_temperature():
    pressures = [saturation_pressure_pa(t) for t, *_ in NIST_SATURATION_TABLE]
    assert all(later > earlier for earlier, later in itertools.pairwise(pressures))


def test_saturation_pressure_approaches_the_critical_pressure():
    near_critical = critical_temperature_k() - 0.01
    assert saturation_pressure_pa(near_critical) == pytest.approx(
        critical_pressure_pa(), rel=1e-3
    )


# --- 3. liquid denser than vapour -----------------------------------------


def test_liquid_is_denser_than_vapour_throughout_the_two_phase_domain():
    for temperature, *_ in NIST_SATURATION_TABLE:
        assert saturated_liquid_density_kg_m3(temperature) > saturated_vapour_density_kg_m3(
            temperature
        )


def test_liquid_density_falls_and_vapour_density_rises_with_temperature():
    liquid = [saturated_liquid_density_kg_m3(t) for t, *_ in NIST_SATURATION_TABLE]
    vapour = [saturated_vapour_density_kg_m3(t) for t, *_ in NIST_SATURATION_TABLE]
    assert all(later < earlier for earlier, later in itertools.pairwise(liquid))
    assert all(later > earlier for earlier, later in itertools.pairwise(vapour))


def test_latent_heat_is_positive_and_shrinks_towards_the_critical_point():
    latents = [saturated_state(t).latent_heat_j_kg for t, *_ in NIST_SATURATION_TABLE]
    assert all(value > 0.0 for value in latents)
    assert all(later < earlier for earlier, later in itertools.pairwise(latents))


def test_latent_heat_matches_the_nist_enthalpy_difference():
    for temperature, _p, _rl, _rv, h_l, h_v in NIST_SATURATION_TABLE:
        assert saturated_state(temperature).latent_heat_j_kg == pytest.approx(
            (h_v - h_l) * 1e3, rel=1e-4
        )


def test_internal_energy_is_below_enthalpy_for_both_phases():
    """u = h - p/rho, so u < h wherever p and rho are positive."""
    for temperature, *_ in NIST_SATURATION_TABLE:
        state = saturated_state(temperature)
        assert state.liquid_internal_energy_j_kg < state.liquid_enthalpy_j_kg
        assert state.vapour_internal_energy_j_kg < state.vapour_enthalpy_j_kg
        assert state.liquid_internal_energy_j_kg == pytest.approx(
            state.liquid_enthalpy_j_kg - state.pressure_pa / state.liquid_density_kg_m3,
            rel=1e-9,
        )
        assert state.vapour_internal_energy_j_kg == pytest.approx(
            state.vapour_enthalpy_j_kg - state.pressure_pa / state.vapour_density_kg_m3,
            rel=1e-9,
        )


