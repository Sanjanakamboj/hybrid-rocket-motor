# --- isentropic expansion behaviour ---------------------------------------


def test_isentropic_expansion_lowers_enthalpy_and_density():
    state = saturated_state(293.15)
    h2, rho2 = isentropic_downstream_enthalpy_j_kg(
        state.liquid_entropy_j_kg_k, 0.5 * state.pressure_pa
    )
    assert h2 < state.liquid_enthalpy_j_kg
    assert rho2 < state.liquid_density_kg_m3
    assert h2 > 0.0
    assert rho2 > 0.0


def test_isentropic_expansion_to_the_saturation_pressure_recovers_the_liquid_state():
    """Expanding to the pressure it is already at must change nothing."""
    state = saturated_state(280.0)
    h2, rho2 = isentropic_downstream_enthalpy_j_kg(
        state.liquid_entropy_j_kg_k, state.pressure_pa
    )
    assert h2 == pytest.approx(state.liquid_enthalpy_j_kg, rel=1e-6)
    assert rho2 == pytest.approx(state.liquid_density_kg_m3, rel=1e-6)


def test_deeper_expansion_lowers_enthalpy_further():
    state = saturated_state(293.15)
    enthalpies = [
        isentropic_downstream_enthalpy_j_kg(state.liquid_entropy_j_kg_k, p)[0]
        for p in (4.0e6, 3.0e6, 2.0e6, 1.0e6)
    ]
    assert all(later < earlier for earlier, later in itertools.pairwise(enthalpies))


def test_saturated_state_bundles_agree_with_the_individual_getters():
    for temperature in (215.0, 260.0, 293.15):
        state = saturated_state(temperature)
        assert state.pressure_pa == saturation_pressure_pa(temperature)
        assert state.liquid_density_kg_m3 == saturated_liquid_density_kg_m3(temperature)
        assert state.vapour_density_kg_m3 == saturated_vapour_density_kg_m3(temperature)
        assert state.liquid_enthalpy_j_kg == saturated_liquid_enthalpy_j_kg(temperature)
        assert state.vapour_enthalpy_j_kg == saturated_vapour_enthalpy_j_kg(temperature)
        assert state.liquid_internal_energy_j_kg == saturated_liquid_internal_energy_j_kg(
            temperature
        )
        assert state.liquid_entropy_j_kg_k == saturated_liquid_entropy_j_kg_k(temperature)


